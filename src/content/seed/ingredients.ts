// Conventions (PLAN.md §0 content drafting rule, §2 `ingredients` row):
//   - Bilingual: `name_el` in Greek script (loanwords transliterated as Greeks write them: κινόα,
//     τόφου, κέιλ, σκυρ), `name_en` in English. Slugs match `SLUG_RE` and are unique.
//   - Nutrition is per 100 g edible portion (raw/dry unless the name says otherwise): typical values
//     from USDA FoodData Central reference ranges — `source_note` says so on every row. Oils are
//     884 kcal; lard and tallow are capped at the schema's 900 kcal ceiling.
//   - `unit` is the natural recipe unit; `grams_per_unit` is the weight of ONE such unit (1 for g/ml;
//     egg 50, lemon 100, onion 150, garlic clove 3, tbsp olive oil 13.5, tsp salt 6, slice bread 30).
//   - Prices are a typical Greek supermarket range for the `price_per` basis (kg / l / piece) as of
//     `price_as_of`; `price_note` names the basis (per bunch / head / cube / sheet / 1 g sachet when
//     the piece is not the obvious unit). They are estimates for the meal-price feature, not quotes.
